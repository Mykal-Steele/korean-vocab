#!/usr/bin/env python3
"""Embeds the web fonts so the built page needs nothing from the network.

Google Fonts is the only external request the page makes. That is fine online,
but a shared single file should also render correctly offline — and on a machine
with no Korean font installed, losing Noto Sans KR turns every Hangul word into
tofu boxes. So each family is downloaded, subset to just the characters this site
actually uses, and written out as a base64 @font-face rule.

    python3 tools/build-fonts.py
"""
from __future__ import annotations

import base64
import io
import re
import subprocess
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "css" / "fonts.css"

# A recent Chrome UA is what makes Google Fonts serve woff2 rather than ttf.
UA = ("Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) "
      "Chrome/124.0 Safari/537.36")

FAMILIES = [
    ("IBM Plex Sans", [400, 500, 600, 700]),
    ("IBM Plex Serif", [600]),
    ("IBM Plex Mono", [400, 500]),
    ("Noto Sans KR", [400, 500, 700]),
    ("Noto Sans Thai", [400, 500]),
]

# Sources scanned for the characters that must survive subsetting.
TEXT_SOURCES = [
    ROOT / "index.html",
    ROOT / "assets" / "css" / "styles.css",
    *sorted((ROOT / "assets" / "js").glob("*.js")),
]

ALWAYS = (
    "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
    " .,:;!?'\"()[]{}/\\|-–—_+=*&%#@×·…‘’“”→←↑↓✓×"
)


def used_characters() -> set[str]:
    chars = set(ALWAYS)
    for path in TEXT_SOURCES:
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        # Base64 audio would only ever add ASCII, but strip it for speed.
        text = re.sub(r"data:[^\"']{200,}", "", text)
        chars.update(text)
    return {c for c in chars if c.isprintable() and not c.isspace()} | {" "}


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def face_urls(family: str, weights: list[int], chars: set[str]) -> dict[int, str]:
    """One woff2 per weight, already cut down to `chars`.

    Asking for a plain family gives back dozens of @font-face blocks split by
    unicode-range — Noto Sans KR alone is over a hundred — and picking any one of
    them silently loses most of the Hangul. The `text` parameter makes Google
    return a single face per weight containing exactly the glyphs requested.
    """
    spec = f"{family.replace(' ', '+')}:wght@{';'.join(str(w) for w in weights)}"
    text = urllib.parse.quote("".join(sorted(chars)), safe="")
    css = fetch(f"https://fonts.googleapis.com/css2?family={spec}&text={text}").decode("utf-8")

    found: dict[int, str] = {}
    for block in css.split("@font-face")[1:]:
        weight = re.search(r"font-weight:\s*(\d+)", block)
        url = re.search(r"url\((https://[^)]+)\)", block)
        if weight and url and int(weight.group(1)) in weights:
            found.setdefault(int(weight.group(1)), url.group(1))
    missing = [w for w in weights if w not in found]
    if missing:
        raise SystemExit(f"{family}: no woff2 for weights {missing}")
    return found


def subset(raw: bytes, chars: set[str], python: str) -> bytes:
    source = Path("/tmp/_font_in.woff2")
    target = Path("/tmp/_font_out.woff2")
    source.write_bytes(raw)
    text = "".join(sorted(chars))
    result = subprocess.run([
        python, "-m", "fontTools.subset", str(source),
        f"--text={text}",
        "--flavor=woff2",
        "--layout-features=kern,liga,clig,calt,ccmp,locl,mark,mkmk",
        "--no-hinting",
        "--desubroutinize",
        f"--output-file={target}",
    ], capture_output=True, text=True)
    if result.returncode != 0:
        sys.stderr.write(result.stdout + result.stderr)
        raise SystemExit("subsetting failed")
    data = target.read_bytes()
    source.unlink(missing_ok=True)
    target.unlink(missing_ok=True)
    return data


def main() -> int:
    python = sys.argv[1] if len(sys.argv) > 1 else sys.executable
    chars = used_characters()
    print(f"{len(chars)} distinct characters in use")

    rules = ["/* Generated by tools/build-fonts.py. Do not edit by hand.",
             " * Web fonts subset to the characters this site uses and inlined, so the",
             " * page renders correctly with no network access. */"]
    total = 0

    for family, weights in FAMILIES:
        urls = face_urls(family, weights, chars)
        for weight in weights:
            data = fetch(urls[weight])
            total += len(data)
            encoded = base64.b64encode(data).decode("ascii")
            rules.append(
                "@font-face {\n"
                f"  font-family: '{family}';\n"
                "  font-style: normal;\n"
                f"  font-weight: {weight};\n"
                "  font-display: swap;\n"
                f"  src: url(data:font/woff2;base64,{encoded}) format('woff2');\n"
                "}"
            )
            print(f"  {family} {weight}: {len(data) / 1024:.1f} KB")

    OUT.write_text("\n".join(rules) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} — {total / 1024:.0f} KB of font data")
    return 0


if __name__ == "__main__":
    sys.exit(main())
